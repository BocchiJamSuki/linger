_current = 'zh'


def set_language(code):
    global _current
    _current = code if code in STRINGS else 'en'


def language():
    return _current


def system_language():
    from PySide6.QtCore import QLocale
    return 'zh' if QLocale.system().name().lower().startswith('zh') else 'en'


def tr(key, **values):
    text = STRINGS[_current].get(key) or STRINGS['en'][key]
    return text.format(**values) if values else text


